# ============================================================

_POSE_ID_COLUMNS = [
    "dataset",
    "video_path",
    "start_s",
    "end_s",
    "label",
    "activity",
    "subject",
    "camera",
    "scenario",
]


def _pose_row_key(row):

    values = []

    for column in _POSE_ID_COLUMNS:

        value = getattr(
            row,
            column,
            None,
        )

        if pd.isna(value):

            values.append(
                "<NA>"
            )

        elif isinstance(
            value,
            (float, np.floating),
        ):

            values.append(
                f"{float(value):.6f}"
            )

        else:

            values.append(
                str(value)
            )

    return tuple(
        values
    )


