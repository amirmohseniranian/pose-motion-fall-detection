def _benchmark_read_frames(
    video_path,
    start_s=0.0,
    end_s=None,
    T=32,
):
    """
    Read up to T real RGB frames from one annotated interval.

    Strategy:
      1. Open video.
      2. Compute valid frame interval from fps/frame count.
      3. Try direct seek to the interval.
      4. If seek/decode is insufficient, reopen and sequentially scan.
      5. Return decoded frames plus a status string.

    This helper is benchmark-only and intentionally does not replace
    the canonical `sample_indices()` / `read_sampled_frames()` later
    in the notebook.
    """

    video_path = str(
        video_path
    )

    cap = cv2.VideoCapture(
        video_path
    )

    if not cap.isOpened():
        return (
            [],
            None,
            "open_failed",
        )

    try:

        fps = float(
            cap.get(
                cv2.CAP_PROP_FPS
            )
            or 0.0
        )

        frame_count = int(
            cap.get(
                cv2.CAP_PROP_FRAME_COUNT
            )
            or 0
        )

        if fps <= 0:
            fps = 30.0

        if frame_count <= 0:
            return (
                [],
                fps,
                "no_frames",
            )

        start_s = max(
            0.0,
            float(
                start_s
                if start_s is not None
                else 0.0
            ),
        )

        if (
            end_s is None
            or not np.isfinite(
                float(end_s)
            )
        ):

            end_s = (
                frame_count - 1
            ) / fps

        else:

            end_s = max(
                start_s,
                float(end_s),
            )

        start_idx = min(
            frame_count - 1,
            max(
                0,
                int(
                    round(
                        start_s * fps
                    )
                ),
            ),
        )

        end_idx = min(
            frame_count - 1,
            max(
                start_idx,
                int(
                    round(
                        end_s * fps
                    )
                ),
            ),
        )

        if end_idx < start_idx:
            end_idx = start_idx

        target_indices = (
            np.linspace(
                start_idx,
                end_idx,
                T,
            )
            .round()
            .astype(int)
        )

        target_indices = np.clip(
            target_indices,
            start_idx,
            end_idx,
        )

        unique_targets = {
            int(i)
            for i in np.unique(
                target_indices
            )
        }


        # --------------------------------------------------------
        # Attempt 1:
        # Direct seek to the annotated interval.
        # --------------------------------------------------------

        frame_map = {}

        seek_ok = cap.set(
            cv2.CAP_PROP_POS_FRAMES,
            int(start_idx),
        )

        if seek_ok:

            current_idx = int(
                cap.get(
                    cv2.CAP_PROP_POS_FRAMES
                )
                or start_idx
            )

            # OpenCV backends can report an imprecise seek position.
            # Trust the actual reported/current frame only if it remains
            # within a sensible range; otherwise restart sequentially.
            if current_idx > end_idx:
                current_idx = start_idx

            while (
                current_idx <= end_idx
                and len(frame_map)
                < len(unique_targets)
            ):

                ok, frame = cap.read()

                if not ok:
                    break

                if current_idx in unique_targets:

                    frame_map[
                        current_idx
                    ] = cv2.cvtColor(
                        frame,
                        cv2.COLOR_BGR2RGB,
                    )

                current_idx += 1


        frames = [
            frame_map.get(
                int(idx)
            )
            for idx in target_indices
        ]

        valid_count = sum(
            frame is not None
            for frame in frames
        )


        # --------------------------------------------------------
        # Attempt 2:
        # Sequential fallback from frame 0.
        #
        # This is important for codecs where CAP_PROP_POS_FRAMES
        # succeeds syntactically but lands at a bad position.
        # --------------------------------------------------------

        if valid_count < min(8, T):

            cap.release()

            cap = cv2.VideoCapture(
                video_path
            )

            if not cap.isOpened():

                return (
                    [
                        frame
                        for frame
                        in frames
                        if frame is not None
                    ],
                    fps,
                    "reopen_failed",
                )

            frame_map = {}

            current_idx = 0

            while (
                current_idx <= end_idx
                and len(frame_map)
                < len(unique_targets)
            ):

                ok, frame = cap.read()

                if not ok:
                    break

                if (
                    current_idx >= start_idx
                    and current_idx
                    in unique_targets
                ):

                    frame_map[
                        current_idx
                    ] = cv2.cvtColor(
                        frame,
                        cv2.COLOR_BGR2RGB,
                    )

                current_idx += 1


            frames = [
                frame_map.get(
                    int(idx)
                )
                for idx in target_indices
            ]

            valid_count = sum(
                frame is not None
                for frame in frames
            )


        if valid_count < min(8, T):

            return (
                [
                    frame
                    for frame
                    in frames
                    if frame is not None
                ],
                fps,
                "insufficient_frames",
            )


        # --------------------------------------------------------
        # Fill occasional missing sampled indices from decoded
        # real frames while preserving exactly T inputs.
        # --------------------------------------------------------

        valid_frames = [
            frame
            for frame in frames
            if frame is not None
        ]

        final_frames = []

        for i, frame in enumerate(
            frames
        ):

            if frame is None:

                frame = valid_frames[
                    i % len(valid_frames)
                ]

            final_frames.append(
                frame
            )

        return (
            final_frames,
            fps,
            "ok",
        )

    finally:

        cap.release()


