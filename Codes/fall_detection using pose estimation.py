# ------------------------------------------------------------
# Robust benchmark/extraction reader.
#
# The canonical reader is good for normal operation, but OpenCV's
# random frame seeking can fail on some compressed videos/backends.
#
# This fallback:
#   1. opens the file,
#   2. computes the requested frame indices,
#   3. tries direct seek,
#   4. falls back to sequential decoding from frame zero,
#   5. returns real decoded frames only,
#   6. requires >= 8 valid frames.
#
# It never invents a synthetic frame.
# Missing positions are later filled from other REAL decoded frames
# by `extract_one_pose()`.
# ------------------------------------------------------------

def _robust_read_sampled_frames(
    video_path,
    start_s=0,
    end_s=None,
    T=32,
):
    video_path = str(
        video_path
    )

    cap = cv2.VideoCapture(
        video_path
    )

    if not cap.isOpened():

        raise IOError(
            f"Cannot open video: {video_path}"
        )

    try:

        fps = float(
            cap.get(
                cv2.CAP_PROP_FPS
            )
            or 0
        )

        frame_count = int(
            cap.get(
                cv2.CAP_PROP_FRAME_COUNT
            )
            or 0
        )

        if fps <= 0:
            fps = 30.0

        if frame_count <= 0:

            raise ValueError(
                f"Video has no readable frames: {video_path}"
            )

        start_s = float(
            0.0
            if start_s is None
            else start_s
        )

        if not np.isfinite(
            start_s
        ):
            start_s = 0.0

        start_s = max(
            start_s,
            0.0,
        )

        if (
            end_s is None
            or not np.isfinite(
                float(end_s)
            )
        ):

            end_s = (
                frame_count - 1
            ) / fps

        else:

            end_s = max(
                float(end_s),
                start_s,
            )

        start_idx = min(
            frame_count - 1,
            max(
                0,
                int(
                    round(
                        start_s * fps
                    )
                ),
            ),
        )

        end_idx = min(
            frame_count - 1,
            max(
                start_idx,
                int(
                    round(
                        end_s * fps
                    )
                ),
            ),
        )

        target_indices = (
            np.linspace(
                start_idx,
                end_idx,
                T,
            )
            .round()
            .astype(int)
        )

        target_indices = np.clip(
            target_indices,
            start_idx,
            end_idx,
        )

        wanted = {
            int(i)
            for i in target_indices
        }


        # ========================================================
        # Attempt 1: direct seek
        # ========================================================

        frame_map = {}

        seek_result = cap.set(
            cv2.CAP_PROP_POS_FRAMES,
            start_idx,
        )

        if seek_result:

            current_idx = int(
                cap.get(
                    cv2.CAP_PROP_POS_FRAMES
                )
                or start_idx
            )

            # Some backends report an invalid post-seek position.
            if current_idx < start_idx:
                current_idx = start_idx

            if current_idx <= end_idx:

                while (
                    current_idx <= end_idx
                    and len(frame_map)
                    < len(wanted)
                ):

                    ok, frame = cap.read()

                    if not ok:
                        break

                    if current_idx in wanted:

                        frame_map[
                            current_idx
                        ] = cv2.cvtColor(
                            frame,
                            cv2.COLOR_BGR2RGB,
                        )

                    current_idx += 1


        frames = [
            frame_map.get(
                int(idx)
            )
            for idx in target_indices
        ]

        valid_count = sum(
            frame is not None
            for frame in frames
        )


        # ========================================================
        # Attempt 2: sequential fallback
        # ========================================================

        if valid_count < min(
            8,
            T,
        ):

            cap.release()

            cap = cv2.VideoCapture(
                video_path
            )

            if not cap.isOpened():

                raise IOError(
                    f"Could not reopen video for sequential decoding: "
                    f"{video_path}"
                )

            frame_map = {}

            current_idx = 0

            while (
                current_idx <= end_idx
                and len(frame_map)
                < len(wanted)
            ):

                ok, frame = cap.read()

                if not ok:
                    break

                if (
                    current_idx >= start_idx
                    and current_idx in wanted
                ):

                    frame_map[
                        current_idx
                    ] = cv2.cvtColor(
                        frame,
                        cv2.COLOR_BGR2RGB,
                    )

                current_idx += 1


            frames = [
                frame_map.get(
                    int(idx)
                )
                for idx in target_indices
            ]

            valid_count = sum(
                frame is not None
                for frame in frames
            )


        if valid_count < min(
            8,
            T,
        ):

            raise ValueError(
                "Insufficient readable sampled frames "
                f"({valid_count}/{T}) for video={video_path}, "
                f"interval=[{start_s}, {end_s}]"
            )


        # --------------------------------------------------------
        # Return exactly T entries.
        #
        # Any missing sampled location is replaced by another
        # REAL decoded frame from this same interval.
        # --------------------------------------------------------

        valid_frames = [
            frame
            for frame in frames
            if frame is not None
        ]

        completed = []

        for i, frame in enumerate(
            frames
        ):

            if frame is None:

                frame = valid_frames[
                    i % len(valid_frames)
                ]

            completed.append(
                frame
            )


        times = np.asarray(
            [
                float(
                    idx / fps
                )
                for idx in target_indices
            ],
            dtype=np.float32,
        )

        return (
            completed,
            times,
            float(fps),
        )

    finally:

        cap.release()


