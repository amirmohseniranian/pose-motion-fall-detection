def sample_indices(cap, start_s, end_s, T=32):
    fps = cap.get(cv2.CAP_PROP_FPS) or 30.0
    n = int(cap.get(cv2.CAP_PROP_FRAME_COUNT) or 0)

    if n <= 0:
        raise ValueError("Video has no frames")

    start = max(
        0,
        int(round(start_s * fps))
    )

    end = (
        n - 1
        if end_s is None
        or not np.isfinite(end_s)
        else min(
            n - 1,
            int(round(end_s * fps))
        )
    )

    if end < start:
        end = start

    idx = (
        np.linspace(
            start,
            end,
            T
        )
        .round()
        .astype(int)
    )

    return idx, fps


def read_sampled_frames(
    video_path,
    start_s=0,
    end_s=None,
    T=32,
):
    cap = cv2.VideoCapture(
        str(video_path)
    )

    if not cap.isOpened():
        raise IOError(
            f"Cannot open video: {video_path}"
        )

    idxs, fps = sample_indices(
        cap,
        start_s,
        end_s,
        T
    )

    start_idx = int(
        idxs[0]
    )

    end_idx = int(
        idxs[-1]
    )

    cap.set(
        cv2.CAP_PROP_POS_FRAMES,
        start_idx
    )

    wanted = {
        int(i)
        for i in idxs
    }

    frame_map = {}

    for frame_idx in range(
        start_idx,
        end_idx + 1
    ):

        ok, frame = cap.read()

        if not ok:
            break

        if frame_idx in wanted:

            frame_map[frame_idx] = (
                cv2.cvtColor(
                    frame,
                    cv2.COLOR_BGR2RGB
                )
            )

    cap.release()

    frames = [
        frame_map.get(
            int(i)
        )
        for i in idxs
    ]

    times = np.asarray(
        [
            float(i / fps)
            for i in idxs
        ],
        dtype=np.float32,
    )

    return (
        frames,
        times,
        fps,
    )


def choose_primary_person(
    result,
    prev_center=None
):
    if (
        result.boxes is None
        or len(result.boxes) == 0
        or result.keypoints is None
    ):
        return None, None, None

    xy = (
        result.keypoints.xy
        .detach()
        .cpu()
        .numpy()
    )

    kc = (
        result.keypoints.conf
        .detach()
        .cpu()
        .numpy()
        if result.keypoints.conf is not None
        else np.ones(
            xy.shape[:2],
            dtype=np.float32
        )
    )

    bconf = (
        result.boxes.conf
        .detach()
        .cpu()
        .numpy()
        if result.boxes.conf is not None
        else np.ones(
            len(xy),
            dtype=np.float32
        )
    )

    boxes = (
        result.boxes.xyxy
        .detach()
        .cpu()
        .numpy()
    )

    H, W = result.orig_shape
    img_area = max(
        float(H * W),
        1.0
    )

    best = None

    for i in range(
        len(xy)
    ):

        conf = float(
            np.mean(kc[i])
        )

        area = max(
            0.0,
            float(
                (boxes[i, 2] - boxes[i, 0])
                * (boxes[i, 3] - boxes[i, 1])
            )
        ) / img_area

        cx = float(
            (boxes[i, 0] + boxes[i, 2]) / 2
        )

        cy = float(
            (boxes[i, 1] + boxes[i, 3]) / 2
        )

        continuity = 0.0

        if prev_center is not None:

            diag = (
                H**2 + W**2
            ) ** 0.5

            continuity = max(
                0.0,
                1.0
                - np.hypot(
                    cx - prev_center[0],
                    cy - prev_center[1],
                ) / max(
                    diag,
                    1.0
                )
            )

        score = (
            0.45 * float(bconf[i])
            + 0.30 * conf
            + 0.15 * min(area * 8, 1.0)
            + 0.10 * continuity
        )

        if (
            best is None
            or score > best[0]
        ):
            best = (
                score,
                i,
                (cx, cy),
                xy[i],
                kc[i],
            )

    _, i, center, kpts, kcps = best

    return (
        kpts.astype(
            np.float32
        ),
        kcps.astype(
            np.float32
        ),
        center,
    )


def normalize_skeleton(
    kpts,
    conf
):
    T, V, _ = kpts.shape

    xy = kpts.copy().astype(
        np.float32
    )

    c = conf.copy().astype(
        np.float32
    )

    xy[
        c < KPT_CONF_MIN
    ] = np.nan

    out = np.zeros_like(
        xy,
        dtype=np.float32
    )

    valid_center = []
    valid_scale = []

    for t in range(T):

        def mean_joint(ids):

            pts = [
                xy[t, i]
                for i in ids
                if np.isfinite(
                    xy[t, i]
                ).all()
            ]

            return (
                np.mean(
                    pts,
                    axis=0
                )
                if pts
                else None
            )

        hips = mean_joint(
            [11, 12]
        )

        shoulders = mean_joint(
            [5, 6]
        )

        center = (
            hips
            if hips is not None
            else shoulders
            if shoulders is not None
            else mean_joint(
                list(range(V))
            )
        )

        if center is None:
            center = np.array(
                [np.nan, np.nan],
                dtype=np.float32
            )

        valid_center.append(
            center
        )

        sw = 0.0

        if (
            np.isfinite(
                xy[t, 5]
            ).all()
            and np.isfinite(
                xy[t, 6]
            ).all()
        ):
            sw = float(
                np.linalg.norm(
                    xy[t, 5]
                    - xy[t, 6]
                )
            )

        torso = []

        if (
            hips is not None
            and shoulders is not None
        ):
            torso.append(
                float(
                    np.linalg.norm(
                        hips
                        - shoulders
                    )
                )
            )

        scale = max(
            [
                sw,
                *torso,
                1.0,
            ]
        ) if (
            sw
            or torso
        ) else 1.0

        valid_scale.append(
            scale
        )

    centers = np.asarray(
        valid_center,
        dtype=np.float32
    )

    scales = np.asarray(
        valid_scale,
        dtype=np.float32
    )

    for j in range(2):

        vals = centers[:, j]
        good = np.isfinite(
            vals
        )

        if good.any():

            centers[:, j] = np.interp(
                np.arange(T),
                np.where(good)[0],
                vals[good]
            )

        else:
            centers[:, j] = 0.0

    good = (
        np.isfinite(scales)
        & (scales > 0)
    )

    if good.any():

        scales = np.interp(
            np.arange(T),
            np.where(good)[0],
            scales[good]
        )

    else:

        scales = np.ones(
            T,
            dtype=np.float32
        )

    for t in range(T):

        good = np.isfinite(
            xy[t]
        ).all(axis=-1)

        out[
            t,
            good
        ] = (
            xy[t, good]
            - centers[t]
        ) / max(
            float(scales[t]),
            1e-3
        )

    return out, c


def add_motion_features(
    xy,
    conf,
    times
):
    dt = np.gradient(
        times
    ).astype(
        np.float32
    )

    dt[
        dt < 1e-3
    ] = 1 / 30

    vel = (
        np.gradient(
            xy,
            axis=0
        )
        / dt[:, None, None]
    )

    acc = (
        np.gradient(
            vel,
            axis=0
        )
        / dt[:, None, None]
    )

    speed = np.linalg.norm(
        vel,
        axis=-1,
        keepdims=True
    )

    feat = np.concatenate(
        [
            xy,
            conf[..., None],
            vel,
            acc,
            speed,
        ],
        axis=-1
    )

    feat = np.nan_to_num(
        feat,
        nan=0.0,
        posinf=0.0,
        neginf=0.0
    ).astype(
        np.float32
    )

    return feat


def pose_cache_path(row):
    key = (
        f"{row.dataset}|"
        f"{Path(row.video_path).as_posix()}|"
        f"{row.start_s:.4f}|"
        f"{row.end_s if pd.notna(row.end_s) else 'END'}|"
        f"{row.label}|"
        f"{row.activity}"
    )

    digest = hashlib.sha1(
        key.encode()
    ).hexdigest()[:20]

    return (
        POSE_DIR
        / f"{row.dataset}_{digest}.npz"
    )


def extract_one_pose(row):

    out_path = pose_cache_path(
        row
    )

    if out_path.exists():

        try:

            with np.load(
                out_path,
                allow_pickle=False
            ) as z:

                if (
                    z["features"].shape
                    == (32, 17, 8)
                    and int(z["label"])
                    == int(row.label)
                    and str(
                        z["cache_version"]
                    )
                    == CACHE_VERSION
                ):
                    return (
                        out_path,
                        True
                    )

        except Exception:
            pass

        out_path.unlink(
            missing_ok=True
        )

    frames, times, fps = (
        read_sampled_frames(
            row.video_path,
            float(row.start_s),
            row.end_s
            if pd.notna(row.end_s)
            else None,
            32,
        )
    )

    valid = [
        f
        for f in frames
        if f is not None
    ]

    if len(valid) < 8:

        raise ValueError(
            "Insufficient readable sampled "
            f"frames ({len(valid)}/32)"
        )

    # Failed frame decoding is represented by a zero image.
    images = [
        f
        if f is not None
        else np.zeros_like(
            valid[0]
        )
        for f in frames
    ]

    if torch.cuda.is_available():
        torch.cuda.reset_peak_memory_stats()

    # Note:
    # A single call contains the entire 32-frame segment and explicitly
    # requests batched inference + FP16 on CUDA/T4.
    results = pose_model.predict(
        source=images,
        imgsz=POSE_IMAGE_SIZE,
        batch=POSE_INFER_BATCH,
        conf=0.15,
        iou=0.70,
        max_det=10,
        half=POSE_FP16,
        device=(
            0
            if torch.cuda.is_available()
            else "cpu"
        ),
        verbose=False,
        stream=False,
    )

    assert_vram_budget(
        "pose inference"
    )

    kpts = []
    confs = []
    prev_center = None

    for result in results:

        kp, kc, center = (
            choose_primary_person(
                result,
                prev_center
            )
        )

        if kp is None:

            kpts.append(
                np.full(
                    (17, 2),
                    np.nan,
                    dtype=np.float32
                )
            )

            confs.append(
                np.zeros(
                    17,
                    dtype=np.float32
                )
            )

        else:

            kpts.append(kp)
            confs.append(kc)
            prev_center = center

    xy = np.stack(
        kpts
    )

    cf = np.stack(
        confs
    )

    xy, cf = normalize_skeleton(
        xy,
        cf
    )

    features = add_motion_features(
        xy,
        cf,
        times
    )

    tmp = out_path.with_suffix(
        ".tmp.npz"
    )

    np.savez_compressed(
        tmp,
        features=features,
        label=np.int64(row.label),
        dataset=str(row.dataset),
        subject=str(row.subject),
        camera=np.int64(
            row.camera
            if pd.notna(row.camera)
            else -1
        ),
        activity=str(row.activity),
        scenario=str(row.scenario),
        video_path=str(row.video_path),
        start_s=np.float32(
            row.start_s
        ),
        end_s=np.float32(
            row.end_s
            if pd.notna(row.end_s)
            else times[-1]
        ),
        fps=np.float32(fps),
        cache_version=CACHE_VERSION,
    )

    os.replace(
        tmp,
        out_path
    )

    return (
        out_path,
        False
    )


def ensure_pose_manifest(
    input_df,
    manifest_path,
    desc,
    essential=True,
    checkpoint_every=20,
):
    """Extract pose features for the requested rows with resumable caching."""

    if input_df.empty:
        return pd.DataFrame()

    input_df = (
        input_df
        .copy()
        .reset_index(drop=True)
    )

    rows = []
    errors = []

    for i, row in tqdm(
        input_df.iterrows(),
        total=len(input_df),
        desc=desc,
    ):

        BUDGET.guard(
            "pose_extraction",
            essential=essential
        )

        try:

            p, cache_hit = extract_one_pose(
                row
            )

            rows.append({
                **row.to_dict(),
                "pose_path": str(p),
                "pose_cache_hit": cache_hit,
                "pose_cache_version": CACHE_VERSION,
            })

        except BudgetStop:
            raise

        except Exception as e:

            errors.append({
                **row.to_dict(),
                "error": repr(e),
            })

        if (
            (i + 1)
#             % checkpoint_every
            == 0
        ):

            BUDGET.checkpoint(
                f"{desc}_checkpoint_{i+1}"
            )

    out = pd.DataFrame(
        rows
    )

    out.to_csv(
        manifest_path,
        index=False
    )

    if errors:

        pd.DataFrame(
            errors
        ).to_csv(
            DIRS["logs"]
            / (
                Path(manifest_path).stem
                + "_errors.csv"
            ),
            index=False
        )

        print(
            f"[WARN] {desc}: "
            f"{len(errors)} pose failures logged."
        )

    return out

